-- ---------------------------------------------------------------- stats: visits and games played, all time
create table if not exists public.site_stats (key text primary key, value bigint not null default 0);
alter table public.site_stats enable row level security;
insert into public.site_stats (key, value) values ('visits', 0), ('games', 0) on conflict (key) do nothing;

create table if not exists public.visitors (device_id text primary key, first_at timestamptz not null default now(), last_at timestamptz not null default now(), visits int not null default 1);
alter table public.visitors enable row level security;

alter table public.rooms add column if not exists last_game_at timestamptz;

-- One visit per device every 30 minutes, so refreshing the page doesn't pump the number.
create or replace function public.log_visit(p_device text) returns void
language plpgsql security definer set search_path = public as $$
declare v_last timestamptz;
begin
  if p_device is null or length(p_device) < 8 or length(p_device) > 64 then return; end if;
  select last_at into v_last from public.visitors where device_id = p_device;
  if v_last is null then
    insert into public.visitors (device_id) values (p_device) on conflict do nothing;
  elsif v_last > now() - interval '30 minutes' then
    update public.visitors set last_at = now() where device_id = p_device; return;
  else
    update public.visitors set last_at = now(), visits = visits + 1 where device_id = p_device;
  end if;
  update public.site_stats set value = value + 1 where key = 'visits';
end;
$$;

-- Counted by the host when an online round starts. At most one per room per minute.
create or replace function public.log_game(p_room uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.rooms set last_game_at = now() where id = p_room and (last_game_at is null or last_game_at < now() - interval '60 seconds');
  if found then update public.site_stats set value = value + 1 where key = 'games'; end if;
end;
$$;

create or replace function public.get_stats()
returns table (visits bigint, games bigint, players bigint)
language sql stable security definer set search_path = public as $$
  select (select value from public.site_stats where key = 'visits'),
         (select value from public.site_stats where key = 'games'),
         (select count(*) from public.visitors);
$$;

grant execute on function public.log_visit(text), public.log_game(uuid), public.get_stats() to anon, authenticated;
